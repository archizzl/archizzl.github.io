"""
Static pages for the portfolio galleries, so shared links get a proper
preview (title, description, image). Link-preview crawlers (iMessage, Slack,
Discord, X...) don't run JavaScript, so the tags have to be in the HTML.

For each gallery in hpi/gallery/galleries.json this writes:
    <id>/index.html         the gallery page (grid), e.g. /photo/
    <id>/<key>/index.html   one page per item, e.g. /photo/P1110848_nxzora/

Both just load hpi/gallery/gallery.js, which opens the viewer on that item.
Item keys and order must match arrange() in gallery.js: an image's key is its
Cloudinary public ID, an embed or link's is slug(title) (or of its URL), with
-2, -3... added to repeats.

Images come from Cloudinary's tag list, like gallery.js. If that can't be
fetched, <id>/photos.json is used and stale item pages are left alone. A
newly tagged image has no page until the next build, but 404.html sends
/<id>/<key>/ on to /<id>/?item=<key>, which still opens it.

It also stamps gallery.js and gallery.css with a content hash (?v=...) in
these pages and in the homepage's index.html. Cloudflare in front of the site
caches .js/.css for hours, so without a new URL a change to gallery.js
wouldn't reach visitors until that expired.

Run by blog/build.py (npm run build, npm run dev).
"""

import hashlib
import json
import re
import urllib.request
from html import escape
from pathlib import Path

SITE_ROOT = Path(__file__).resolve().parent.parent
GALLERY_DIR = SITE_ROOT / "hpi" / "gallery"
CLOUD = "https://res.cloudinary.com/do45g1bvk/image/"  # same as gallery.js
OG_IMAGE = "c_limit,w_1200,h_1200,f_jpg,q_auto"
OG_MAX = 1200
MARKER = "<!-- generated by blog/gallery_pages.py"
# Keys that can be a folder name; anything else is only reachable as ?item=.
# gallery.js uses the same rule when it puts the key in the address bar.
PATH_SAFE = re.compile(r"^[A-Za-z0-9_-][A-Za-z0-9_.-]*$")


def versioned(name: str) -> str:
    """/hpi/gallery/<name>?v=<hash of its contents>."""
    digest = hashlib.sha1((GALLERY_DIR / name).read_bytes()).hexdigest()[:10]
    return f"/hpi/gallery/{name}?v={digest}"


def stamp_index() -> bool:
    """Point index.html's gallery.js/css tags at the current versions."""
    index = SITE_ROOT / "index.html"
    text = index.read_text(encoding="utf-8")
    new = text
    for name in ("gallery.js", "gallery.css"):
        url = versioned(name).lstrip("/")
        new = re.sub(r'(["\'])/?hpi/gallery/' + re.escape(name) + r'(\?v=[0-9a-f]*)?(["\'])',
                     lambda m: m.group(1) + url + m.group(3), new)
    if new == text:
        return False
    index.write_text(new, encoding="utf-8")
    return True


def site_url() -> str:
    cname = SITE_ROOT / "CNAME"
    host = cname.read_text().strip() if cname.exists() else "archizzl.github.io"
    return f"https://{host}"


def slug(s) -> str:
    s = str(s or "").lower()
    s = re.sub(r"^https?://(www\.)?", "", s)
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s[:60]


def is_image(item) -> bool:
    return isinstance(item, str)


def tagged_images(cfg: dict) -> tuple[list[str], dict, bool]:
    """(public IDs newest first, {id: (width, height)}, came from Cloudinary)."""
    try:
        url = CLOUD + "list/" + urllib.request.quote(cfg["tag"]) + ".json"
        with urllib.request.urlopen(url, timeout=10) as r:
            res = json.load(r)["resources"]
        res.sort(key=lambda x: x.get("created_at", ""), reverse=True)
        if res:
            sizes = {x["public_id"]: (x.get("width"), x.get("height")) for x in res}
            return [x["public_id"] for x in res], sizes, True
    except Exception as e:  # noqa: BLE001
        print(f"gallery {cfg['id']}: couldn't read Cloudinary tag ({e}), using photos.json")
    fallback = GALLERY_DIR / cfg["id"] / "photos.json"
    ids = json.loads(fallback.read_text()) if fallback.exists() else []
    return ids, {}, False


def arrange(images: list[str], config: dict | None) -> list[dict]:
    """Items in viewer order as {item, key, section, description}."""
    config = config or {}
    hidden = {i for i in config.get("hidden", []) if is_image(i)}
    tagged = {i for i in images if i not in hidden}
    used: set[str] = set()
    groups = []
    for sec in config.get("sections", []):
        items = []
        for item in sec.get("items") or sec.get("photos") or []:
            if not is_image(item):
                t = (item or {}).get("type")
                if (t == "embed" and item.get("src")) or (t == "link" and item.get("url")):
                    items.append(item)
            elif item in tagged and item not in used:
                used.add(item)
                items.append(item)
        if items:
            groups.append((sec.get("title", ""), sec.get("description", ""), items))
    rest = [i for i in images if i in tagged and i not in used]
    if rest:
        groups.append(("", "", rest))

    out, seen = [], set()
    for title, desc, items in groups:
        for item in items:
            key = item if is_image(item) else (
                slug(item.get("title")) or slug(item.get("url") or item.get("src")) or "item")
            base, n = key, 2
            while key in seen:
                key, n = f"{base}-{n}", n + 1
            seen.add(key)
            out.append({"item": item, "key": key, "section": title, "description": desc})
    return out


def image_url(src: str) -> str:
    return src if re.match(r"^https?://", src) else CLOUD + "upload/" + OG_IMAGE + "/" + src


def plain(text: str, limit: int = 200) -> str:
    """Description text for a meta tag: [text](url) links become text."""
    text = re.sub(r"\[([^\]]+)\]\([^)\s]+\)", r"\1", text or "")
    text = " ".join(text.split())
    if len(text) > limit:
        text = text[:limit].rsplit(" ", 1)[0].rstrip(",.;:") + "…"
    return text


def page(cfg: dict, url: str, title: str, og_title: str, desc: str,
         image: str, size, key: str = "") -> str:
    e = lambda s: escape(s, quote=True)  # noqa: E731
    meta = [
        f'<link rel="canonical" href="{e(url)}">',
        '<meta property="og:type" content="website">',
        '<meta property="og:site_name" content="archie o\'connell">',
        f'<meta property="og:title" content="{e(og_title)}">',
        f'<meta property="og:url" content="{e(url)}">',
    ]
    if desc:
        meta.insert(0, f'<meta name="description" content="{e(desc)}">')
        meta.append(f'<meta property="og:description" content="{e(desc)}">')
    if image:
        meta.append(f'<meta property="og:image" content="{e(image)}">')
        if size and size[0] and size[1]:
            w, h = size
            scale = min(1, OG_MAX / max(w, h))
            meta.append(f'<meta property="og:image:width" content="{round(w * scale)}">')
            meta.append(f'<meta property="og:image:height" content="{round(h * scale)}">')
        meta.append('<meta name="twitter:card" content="summary_large_image">')
    item_attr = f' data-gallery-item="{e(key)}"' if key else ""
    head = "\n  ".join(meta)
    return f"""<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  {MARKER} from hpi/gallery/ — edit that, not this. -->
  <title>{e(title)}</title>
  <meta name="viewport" content="width=device-width, initial-scale=0.7">
  {head}
  <link rel="icon" type="image/x-icon" href="/favicon.ico">
  <link rel="stylesheet" href="/index.css">
  <link rel="stylesheet" href="{e(versioned('gallery.css'))}">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible:ital,wght@0,400;0,700;1,400;1,700&display=swap" rel="stylesheet">
</head>
<body>
  <!-- The gallery opens over this on load; closing it goes to the homepage. -->
  <div data-gallery-page="{e(cfg['id'])}"{item_attr}><a href="/">← home</a></div>
  <script src="{e(versioned('gallery.js'))}"></script>
</body>
</html>
"""


def write(path: Path, text: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def build_gallery_pages() -> None:
    if stamp_index():
        print("index.html: updated gallery.js/css versions")
    galleries = json.loads((GALLERY_DIR / "galleries.json").read_text())
    base = site_url()
    for cfg in galleries:
        gid, label = cfg["id"], cfg["label"]
        out_dir = SITE_ROOT / gid
        sections_path = GALLERY_DIR / gid / "sections.json"
        config = json.loads(sections_path.read_text()) if sections_path.exists() else {}
        images, sizes, live = tagged_images(cfg)
        items = arrange(images, config)

        featured = [i for i in config.get("featured", []) if i in sizes or (not live and i in images)]
        cover = featured[0] if featured else next((x["item"] for x in items if is_image(x["item"])), "")
        changed = write(out_dir / "index.html", page(
            cfg, f"{base}/{gid}/", label, label,
            "", image_url(cover) if cover else "", sizes.get(cover)))

        keep = set()
        for x in items:
            item, key = x["item"], x["key"]
            if not PATH_SAFE.match(key):
                continue
            keep.add(key)
            name = x["section"] if is_image(item) else (item.get("title") or x["section"])
            name = name or label
            if is_image(item):
                img, size = image_url(item), sizes.get(item)
            else:
                img, size = (image_url(item["thumb"]) if item.get("thumb") else
                             image_url(cover) if cover else ""), sizes.get(item.get("thumb"))
            # Just the item's or section's own title, nothing added
            # (gallery.js titleFor() matches).
            changed |= write(out_dir / key / "index.html", page(
                cfg, f"{base}/{gid}/{key}/", name, name,
                plain(x["description"]), img, size, key))

        # Remove pages for items that are gone, but only ones we generated,
        # and only when the image list is the live one.
        removed = 0
        if live:
            for d in out_dir.iterdir():
                f = d / "index.html"
                if d.is_dir() and d.name not in keep and f.exists() and MARKER in f.read_text(encoding="utf-8"):
                    f.unlink()
                    if not any(d.iterdir()):
                        d.rmdir()
                    removed += 1
        if changed or removed:
            print(f"gallery {gid}: {len(keep)} item page(s)" + (f", removed {removed}" if removed else ""))


if __name__ == "__main__":
    build_gallery_pages()
